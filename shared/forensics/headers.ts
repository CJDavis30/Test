/**
 * Email header forensics. Headers record the route a message took and when each machine saw it, in that machine's own words. Read
 * carefully they say a lot: the sender's local timezone (from the Date line), the first server that accepted the message and its IP,
 * how long each hop took, whether SPF/DKIM/DMARC passed, and whether the story the message tells about itself holds together.
 */
export interface Hop { index: number; from?: string; by?: string; with?: string; ip?: string; at?: number; tz?: string; delaySec?: number; raw: string }
export interface HeaderFinding { level: 'info' | 'warn' | 'bad'; text: string }
export interface HeaderReport {
  from?: string; to?: string; subject?: string; messageId?: string; replyTo?: string; returnPath?: string; mailer?: string;
  /** when the sender's client stamped it, with the timezone the sender's computer was set to */
  sent?: { at: number; tz: string; offsetMin: number };
  hops: Hop[];
  auth: { spf?: string; dkim?: string; dmarc?: string };
  originIp?: string;
  findings: HeaderFinding[];
}

const unfold = (t: string) => t.replace(/\r?\n[ \t]+/g, ' ');
const grab = (h: string, name: string) => h.match(new RegExp(`^${name}:[ \\t]*(.*)$`, 'im'))?.[1]?.trim();
const IP4 = /\b(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)\b/;
const isPrivate = (ip: string) => /^(10\.|127\.|192\.168\.|169\.254\.|172\.(1[6-9]|2\d|3[01])\.)/.test(ip);

function parseDate(v?: string): { at: number; tz: string; offsetMin: number } | undefined {
  if (!v) return undefined;
  const m = v.match(/([+-])(\d{2})(\d{2})\s*(?:\(.*\))?\s*$/);
  const at = Date.parse(v.replace(/\s*\(.*\)\s*$/, ''));
  if (!Number.isFinite(at)) return undefined;
  const offsetMin = m ? (m[1] === '-' ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0;
  const sign = offsetMin < 0 ? '−' : '+', a = Math.abs(offsetMin);
  return { at, tz: `UTC${sign}${String(Math.floor(a / 60)).padStart(2, '0')}:${String(a % 60).padStart(2, '0')}`, offsetMin };
}

export function analyzeHeaders(text: string): HeaderReport | null {
  const head = unfold(text.slice(0, 200_000).split(/\r?\n\r?\n/)[0]);
  if (!/^Received:/im.test(head) && !/^From:/im.test(head)) return null;
  const receivedRaw = [...head.matchAll(/^Received:[ \t]*(.*)$/gim)].map((m) => m[1]);
  // Received lines are added at the top as the message travels, so the LAST one is the first hop.
  const hops: Hop[] = receivedRaw.reverse().map((raw, i) => {
    const date = parseDate(raw.split(';').pop()?.trim());
    const from = raw.match(/\bfrom\s+(\S+)/i)?.[1], by = raw.match(/\bby\s+(\S+)/i)?.[1], withP = raw.match(/\bwith\s+(\S+)/i)?.[1];
    const ips = [...raw.matchAll(new RegExp(IP4.source, 'g'))].map((m) => m[0]).filter((x) => !isPrivate(x));
    return { index: i + 1, from, by, with: withP, ip: ips[0], at: date?.at, tz: date?.tz, raw: raw.slice(0, 400) };
  });
  for (let i = 1; i < hops.length; i++) if (hops[i].at !== undefined && hops[i - 1].at !== undefined) hops[i].delaySec = Math.round((hops[i].at! - hops[i - 1].at!) / 1000);

  const sent = parseDate(grab(head, 'Date'));
  const auth = grab(head, 'Authentication-Results') ?? '';
  const spf = auth.match(/spf=(\w+)/i)?.[1] ?? grab(head, 'Received-SPF')?.split(/\s/)[0];
  const dkim = auth.match(/dkim=(\w+)/i)?.[1], dmarc = auth.match(/dmarc=(\w+)/i)?.[1];
  const from = grab(head, 'From'), replyTo = grab(head, 'Reply-To'), returnPath = grab(head, 'Return-Path'), messageId = grab(head, 'Message-ID');
  const xip = grab(head, 'X-Originating-IP')?.replace(/[\[\]]/g, '').match(IP4)?.[0];
  const originIp = xip ?? hops.find((h) => h.ip)?.ip;
  const addr = (v?: string) => v?.match(/<([^>]+)>/)?.[1]?.toLowerCase() ?? v?.match(/[^\s<>]+@[^\s<>]+/)?.[0]?.toLowerCase();
  const dom = (v?: string) => addr(v)?.split('@')[1];

  const findings: HeaderFinding[] = [];
  if (sent) findings.push({ level: 'info', text: `The sender's computer was set to ${sent.tz} when this was sent. That is a strong hint about where they were, unless they changed their clock or the message was generated by a service.` });
  if (spf && !/pass/i.test(spf)) findings.push({ level: 'warn', text: `SPF result was “${spf}”: the sending server may not be authorised to send for this domain.` });
  if (dkim && !/pass/i.test(dkim)) findings.push({ level: 'warn', text: `DKIM result was “${dkim}”: the message signature is missing or did not verify.` });
  if (dmarc && !/pass/i.test(dmarc)) findings.push({ level: 'warn', text: `DMARC result was “${dmarc}”.` });
  if (replyTo && dom(replyTo) && dom(from) && dom(replyTo) !== dom(from)) findings.push({ level: 'warn', text: `Replies would go to ${addr(replyTo)}, a different domain from the sender (${addr(from)}). A common impersonation pattern.` });
  if (returnPath && dom(returnPath) && dom(from) && dom(returnPath) !== dom(from)) findings.push({ level: 'info', text: `The envelope sender (${addr(returnPath)}) differs from the visible sender. Normal for mailing services, suspicious otherwise.` });
  const back = hops.find((h) => h.delaySec !== undefined && h.delaySec < -120);
  if (back) findings.push({ level: 'bad', text: `Hop ${back.index} is stamped ${Math.abs(back.delaySec!)} seconds BEFORE the hop that handed it over. Clocks drift, but this much can mean a forged Received line.` });
  const slow = hops.find((h) => h.delaySec !== undefined && h.delaySec > 6 * 3600);
  if (slow) findings.push({ level: 'info', text: `Hop ${slow.index} waited ${Math.round(slow.delaySec! / 3600)} hours before being passed on (queued or held).` });
  const first = hops[0];
  if (sent && first?.at !== undefined && first.at < sent.at - 600_000) findings.push({ level: 'bad', text: 'The first server received it before the sender says they sent it. The Date line may have been set by hand.' });
  if (first?.ip && first.with && /\b(webmail|http)\b/i.test(first.with)) findings.push({ level: 'info', text: `Sent through a web interface from ${first.ip}: the address is the sender's own connection, not a mail server.` });
  if (!hops.length) findings.push({ level: 'info', text: 'No Received lines: this is probably not the full original header.' });
  return { from, to: grab(head, 'To'), subject: grab(head, 'Subject'), messageId, replyTo, returnPath, mailer: grab(head, 'X-Mailer') ?? grab(head, 'User-Agent'), sent, hops, auth: { spf, dkim, dmarc }, originIp, findings };
}
